const rowCache = new Map<string, string[]>();

/** Returns the seven pixel rows of a glyph, or the blank glyph if we have none. */
export function glyphRows(ch: string): string[] {
  const key = ch.toUpperCase();
  const cached = rowCache.get(key);
  if (cached) return cached;
  const encoded = GLYPHS[key] ?? GLYPHS[' '];
  const rows = encoded.split('/');
  rowCache.set(key, rows);
  return rows;
}

/** Width in pixels of a string rendered at the given scale (no trailing spacing). */
export function measureText(text: string, scale = 1): number {
  if (text.length === 0) return 0;
  return (text.length * GLYPH_ADVANCE - (GLYPH_ADVANCE - GLYPH_WIDTH)) * scale;
}
